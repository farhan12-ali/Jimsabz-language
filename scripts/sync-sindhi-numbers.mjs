// Canonical vocabulary: core/sindhi-numbers.json. Regenerate JS, CSV and native data.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const ui=fs.existsSync(path.join(root,'dist/core'))?'dist':'studio';
const data=JSON.parse(fs.readFileSync(path.join(root,ui,'core/sindhi-numbers.json'),'utf8'));
fs.writeFileSync(path.join(root,ui,'core/sindhi-numbers-data.mjs'),'// Generated by scripts/sync-sindhi-numbers.mjs\nexport default '+JSON.stringify(data)+';\n');
const {sindhiWord,sindhiLiteral,sindhiIdentifier}=await import('../'+ui+'/core/sindhi-numbers.mjs?generated='+Date.now());
const rows=['number,roman_sindhi,literal,suggested_identifier'];
for(let n=0;n<=1000;n++)rows.push([n,sindhiWord(n),sindhiLiteral(n),sindhiIdentifier(n)].join(','));
fs.writeFileSync(path.join(root,ui,'assets/Sindhi-Numbers-0-1000.csv'),rows.join('\n')+'\n');
const native=process.argv.includes('--native')?process.argv[process.argv.indexOf('--native')+1]:fs.existsSync(path.join(root,'include/sindhi_numbers.hpp'))?root:null;
if(native){
 const file=path.join(native,'include/sindhi_numbers.hpp');
 let header=fs.readFileSync(file,'utf8');
 header=header.replace(/words=\{.*?\};return words/s,'words={'+data.canonical_0_99.map(word=>JSON.stringify(word)).join(',')+'};return words');
 header=header.replace(/out\["hikro"\].*?return out;/s,Object.entries(data.aliases).map(([word,n])=>'out['+JSON.stringify(word)+']='+n+';').join('')+'return out;');
 fs.writeFileSync(file,header);
}
console.log('Generated JS vocabulary, 1,001 CSV rows'+(native?' and native table.':'.'));
