function unpack(bytes) {
  assert.equal(new TextDecoder().decode(bytes.slice(-16, -8)), 'JIMEXE2!');
  const length = Number(new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength).getBigUint64(bytes.length - 8, true));
  const payload = bytes.slice(bytes.length - length - 16, -16), view = new DataView(payload.buffer); let pos = 0;
  const u32 = () => { const n = view.getUint32(pos, true); pos += 4; return n; };
  const str = () => { const n = u32(), value = payload.slice(pos, pos + n); pos += n; return value; };
  const bytecode = str(), count = u32(), assets = [];
  for (let i = 0; i < count; i++) assets.push({ path: new TextDecoder().decode(str()), bytes: str() });
  assert.equal(pos, payload.length);
  return { bytecode, assets, payload, trailer: bytes.slice(-16), prefix: bytes.slice(0, bytes.length - length - 16) };
}
